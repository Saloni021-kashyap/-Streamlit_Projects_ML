import pickle
from pathlib import Path

import pandas as pd
import streamlit as st

st.set_page_config(page_title="Student Depression Prediction", page_icon="📊")


FEATURE_COLUMNS = [
    "Gender",
    "Age",
    "Family_background",
    "Living_style",
    "Current_semester",
    "CGPA",
    "friend_circle",
    "Health_condition",
    "Cost_without_study",
    "Relationship_status_Complicated",
    "Relationship_status_In a Relationship",
    "Relationship_status_Single",
    "Marital_status_Married",
    "Marital_status_Separated",
    "Marital_status_Unmarried",
]


@st.cache_resource
def load_model():
    model_path = Path(__file__).with_name("model.pkl")
    if not model_path.is_file():
        st.error(f"Could not find the model file: {model_path}")
        st.stop()

    with model_path.open("rb") as model_file:
        return pickle.load(model_file)


model = load_model()

st.title("Student Depression Prediction")
st.write(
    "Enter the student's information to get a prediction from the trained "
    "Random Forest model."
)

with st.form("prediction_form"):
    st.subheader("Student information")
    col1, col2 = st.columns(2)

    with col1:
        gender = st.selectbox("Gender", ["Female", "Male"])
        age = st.number_input("Age", min_value=17, max_value=28, value=20, step=1)
        family_background = st.selectbox(
            "Family background",
            ["Lower Middle class", "Middle class", "Rich class"],
        )
        relationship_status = st.selectbox(
            "Relationship status",
            ["Complicated", "In a Relationship", "Single"],
        )
        marital_status = st.selectbox(
            "Marital status",
            ["Married", "Separated", "Unmarried"],
        )
        living_style = st.selectbox("Living style", ["Bachelor", "Family"])

    with col2:
        current_semester = st.number_input(
            "Current semester", min_value=0, max_value=13, value=1, step=1
        )
        cgpa = st.number_input(
            "CGPA", min_value=2.25, max_value=4.0, value=3.0, step=0.01
        )
        friend_circle = st.selectbox("Have a friend circle?", ["Yes", "No"])
        health_condition = st.selectbox(
            "Health condition", ["Good", "Normal", "Abnormal", "Critical"]
        )
        cost_without_study = st.number_input(
            "Cost without study",
            min_value=0,
            max_value=32000,
            value=10000,
            step=500,
        )

    submitted = st.form_submit_button("Predict")

if submitted:
    relationship_values = {
        "Relationship_status_Complicated": int(
            relationship_status == "Complicated"
        ),
        "Relationship_status_In a Relationship": int(
            relationship_status == "In a Relationship"
        ),
        "Relationship_status_Single": int(relationship_status == "Single"),
    }
    marital_values = {
        "Marital_status_Married": int(marital_status == "Married"),
        "Marital_status_Separated": int(marital_status == "Separated"),
        "Marital_status_Unmarried": int(marital_status == "Unmarried"),
    }

    input_values = {
        "Gender": {"Male": 0, "Female": 1}[gender],
        "Age": age,
        "Family_background": {
            "Lower Middle class": 1,
            "Middle class": 2,
            "Rich class": 3,
        }[family_background],
        "Living_style": {"Bachelor": 0, "Family": 1}[living_style],
        "Current_semester": current_semester,
        "CGPA": cgpa,
        "friend_circle": {"No": 0, "Yes": 1}[friend_circle],
        "Health_condition": {
            "Good": 3,
            "Normal": 2,
            "Abnormal": 1,
            "Critical": 0,
        }[health_condition],
        "Cost_without_study": cost_without_study,
        **relationship_values,
        **marital_values,
    }
    input_data = pd.DataFrame(
        [[input_values[column] for column in FEATURE_COLUMNS]],
        columns=FEATURE_COLUMNS,
    )
    prediction = model.predict(input_data)[0]

    if prediction == 1:
        st.warning("The model predicts signs of depression.")
    else:
        st.success("The model does not predict signs of depression.")

st.caption(
    "This prediction is generated by a machine-learning model and is not a "
    "clinical diagnosis."
)